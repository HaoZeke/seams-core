#!/usr/bin/env python3
"""Performance tables for neighbours and rings, 4096 to 110592 molecules.

Every cell is a field of benchmarks/*.csv from
bench/h2h-mdapy-pyscal3-vesin (5666880e). Quartiles are the interval
stored in the file. A blank time, or a verdict of absent or DNF, is
written DNF. --check refuses a number that is not a CSV token.
"""

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BENCH = ROOT / "benchmarks"
OUT = ROOT / "docs" / "source" / "explanation" / "performance-range-tables.rst"
LO = 4096
HI = 110592
TIME_KEYS = (
    "median_ms",
    "q1_ms",
    "q3_ms",
    "iqr_ms",
    "min_ms",
    "dseams_median_ms",
    "dseams_min_ms",
    "other_median_ms",
    "other_min_ms",
)
SHOW = (
    "competitor",
    "code",
    "version",
    "operation",
    "variant",
    "phase",
    "molecules",
    "threads",
    "n",
    *TIME_KEYS,
    "verdict",
    "source_commit",
    "ratio_vs_dseams",
    "ratio_lo",
    "ratio_hi",
)
RATIO_FILE = BENCH / "paper-numbers" / "sitting-large.csv"
RATIO_OPS = {"classifier", "ptm-default", "ptm-ice", "ira"}
RATIO_SHOW = (
    "code",
    "operation",
    "phase",
    "molecules",
    "threads",
    "n",
    "source_commit",
    "ratio_vs_dseams",
    "ratio_lo",
    "ratio_hi",
)
HEADER = {
    "competitor": "competitor",
    "code": "code",
    "version": "version",
    "operation": "operation",
    "variant": "variant",
    "phase": "phase",
    "molecules": "molecules",
    "threads": "threads",
    "n": "n",
    "median_ms": "median ms",
    "q1_ms": "q1 ms",
    "q3_ms": "q3 ms",
    "iqr_ms": "iqr ms",
    "min_ms": "min ms",
    "dseams_median_ms": "d-SEAMS median ms",
    "dseams_min_ms": "d-SEAMS min ms",
    "other_median_ms": "other median ms",
    "other_min_ms": "other min ms",
    "verdict": "verdict",
    "source_commit": "commit",
    "ratio_vs_dseams": "ratio of medians",
    "ratio_lo": "ratio lo",
    "ratio_hi": "ratio hi",
}
NUMBER = re.compile(r"\d+(?:\.\d+)?(?:[eE][+-]?\d+)?")


def read_csv(path):
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def operation_of(row):
    return (row.get("operation") or row.get("variant") or "").lower()


def ratio_row(row):
    return operation_of(row) in RATIO_OPS


def wanted(row):
    kind = operation_of(row)
    if "neighbour" not in kind and "ring" not in kind:
        return False
    raw = (row.get("molecules") or "").strip()
    if not raw:
        return False
    size = int(float(raw))
    return LO <= size <= HI


def is_dnf(row):
    verdict = (row.get("verdict") or "").strip().lower()
    if verdict in {"absent", "dnf"}:
        return True
    if (row.get("agreement") or "").lstrip().lower().startswith("dnf"):
        return True
    if "median_ms" in row and not (row.get("median_ms") or "").strip():
        return True
    if "dseams_median_ms" in row and not (row.get("dseams_median_ms") or "").strip():
        return True
    return False


def cell(row, key):
    raw = (row.get(key) or "").strip()
    if is_dnf(row) and key in TIME_KEYS:
        return "DNF"
    if is_dnf(row) and key == "verdict":
        return "DNF"
    return raw


def table(path, rows, show=SHOW):
    columns = []
    for key in show:
        if not any(key in row for row in rows):
            continue
        filled = any((row.get(key) or "").strip() for row in rows)
        dnf_time = key in TIME_KEYS and any(is_dnf(row) for row in rows)
        dnf_verdict = key == "verdict" and any(is_dnf(row) for row in rows)
        if filled or dnf_time or dnf_verdict:
            columns.append(key)
    lines = [
        path.name,
        "-" * len(path.name),
        "",
        "Source file ``{}``.".format(path.relative_to(ROOT).as_posix()),
        "",
        ".. csv-table::",
        "   :header: {}".format(", ".join(HEADER[key] for key in columns)),
        "",
    ]
    body = []
    for row in rows:
        shown = [cell(row, key) for key in columns]
        body.append(shown)
        lines.append("   {}".format(", ".join(shown)))
    lines.append("")
    return "\n".join(lines), columns, body


def sections():
    built = []
    for path in sorted(BENCH.glob("*.csv")):
        rows = [row for row in read_csv(path) if wanted(row)]
        if not rows:
            continue
        text, columns, body = table(path, rows)
        built.append((path, rows, text, columns, body))
    if RATIO_FILE.is_file():
        rows = [row for row in read_csv(RATIO_FILE) if ratio_row(row)]
        if rows:
            text, columns, body = table(RATIO_FILE, rows, show=RATIO_SHOW)
            built.append((RATIO_FILE, rows, text, columns, body))
    if not built:
        raise SystemExit("no neighbour or ring rows between 4096 and 110592")
    return built


def render(built):
    blocks = [
        ".. Generated by docs/render_performance_range.py. Edit the CSVs, then rerender.",
        "",
    ]
    for _path, _rows, text, _columns, _body in built:
        blocks.append(text)
    return "\n".join(blocks).rstrip() + "\n"


def tokens_of(text):
    return NUMBER.findall(text)


def check(built):
    errors = []
    corpus = {}
    for path, rows, _text, columns, body in built:
        blob = path.read_text(encoding="utf-8")
        corpus[path] = set(tokens_of(blob))
        for shown in body:
            record = dict(zip(columns, shown))
            for key, value in record.items():
                if value in {"", "DNF"}:
                    continue
                if not any((row.get(key) or "").strip() == value for row in rows):
                    errors.append("{} {}={!r} is not a CSV field".format(path.name, key, value))
                for token in tokens_of(value):
                    if token not in corpus[path]:
                        errors.append("{} number {} is not in the file".format(path.name, token))
    return errors


def main(argv):
    built = sections()
    text = render(built)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    if "--check" in argv:
        errors = check(built)
        page = ROOT / "docs" / "source" / "explanation" / "performance-range.rst"
        if page.is_file():
            allowed = set()
            for path, _rows, _text, _columns, _body in built:
                allowed.update(tokens_of(path.read_text(encoding="utf-8")))
            for token in tokens_of(page.read_text(encoding="utf-8")):
                if token not in allowed:
                    errors.append("performance-range.rst number {} is not in a CSV".format(token))
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1
        print("performance range matches {} csv files".format(len(built)))
    else:
        print("wrote", OUT, "from", len(built), "csv files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
