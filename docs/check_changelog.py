"""Build the 2.14.0 notes from changelog.d and refuse a gap.

Every ``+slug.<type>.md`` fragment is one bullet. A fragment left out of
the render is an orphan. A body that appears twice, or two files that
say the same thing, is a duplicate. The Keep a Changelog types and the
``+`` orphan prefix are the ones in towncrier.toml.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
FRAGMENTS = ROOT / "changelog.d"
NOTES = ROOT / "docs" / "source" / "reference" / "release-2.14-notes.rst"
PAGE = ROOT / "docs" / "orgmode" / "reference" / "release-2.14.org"
TYPES = ("added", "changed", "deprecated", "removed", "fixed", "security")
HEADINGS = {
    "added": "Added",
    "changed": "Changed",
    "deprecated": "Deprecated",
    "removed": "Removed",
    "fixed": "Fixed",
    "security": "Security",
}
NAME = re.compile(r"^\+[A-Za-z0-9][A-Za-z0-9.-]*\.(" + "|".join(TYPES) + r")\.md$")
IGNORED = {"README.md", ".gitkeep"}
CODE = re.compile(r"`([^`]+)`")


def load():
    """Return (errors, fragments) with fragments as (type, name, body)."""
    errors = []
    found = []
    if not FRAGMENTS.is_dir():
        return ["missing changelog.d"], []
    for path in sorted(FRAGMENTS.iterdir()):
        if not path.is_file() or path.name in IGNORED:
            continue
        if path.suffix != ".md":
            errors.append("{} is not a news fragment".format(path.name))
            continue
        match = NAME.fullmatch(path.name)
        if match is None:
            errors.append("{} does not match +slug.<type>.md".format(path.name))
            continue
        body = path.read_text().strip()
        if not body:
            errors.append("{} is empty".format(path.name))
            continue
        found.append((match.group(1), path.name, body))
    seen = {}
    for _typ, name, body in found:
        key = " ".join(body.split())
        if key in seen:
            errors.append("{} repeats {}".format(name, seen[key]))
        else:
            seen[key] = name
    return errors, found


def rst_body(body):
    """Markdown code spans become reStructuredText literals."""
    return CODE.sub(lambda match: "``{}``".format(match.group(1)), body)


def render(fragments):
    lines = [
        ".. Generated by docs/check_changelog.py from changelog.d.",
        ".. Edit the fragment, not this file.",
        "",
    ]
    by_type = {name: [] for name in TYPES}
    for typ, name, body in fragments:
        by_type[typ].append((name, body))
    for typ in TYPES:
        items = by_type[typ]
        if not items:
            continue
        title = HEADINGS[typ]
        lines.append(title)
        lines.append("-" * len(title))
        lines.append("")
        for _name, body in items:
            text = rst_body(body).splitlines()
            lines.append("- {}".format(text[0]))
            for extra in text[1:]:
                lines.append("  {}".format(extra))
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def bullets(text):
    """Bodies of the top-level bullets, with literals restored."""
    found = []
    current = None

    def close():
        nonlocal current
        if current is None:
            return
        body = "\n".join(line for line in current if line != "").strip()
        if body:
            found.append(re.sub(r"``([^`]+)``", r"`\1`", body))
        current = None

    for line in text.splitlines():
        if line.startswith("..") or set(line) <= {"-"} or line.strip() == "":
            if line.strip() == "":
                close()
            continue
        if line.startswith("- "):
            close()
            current = [line[2:]]
            continue
        if current is not None and line.startswith("  "):
            current.append(line[2:])
            continue
        close()
    close()
    return found


def check(fragments, rendered):
    errors = []
    parsed = bullets(rendered)
    wanted = []
    for typ in TYPES:
        wanted.extend(body for kind, _name, body in fragments if kind == typ)
    if parsed != wanted:
        missing = [body for body in wanted if body not in parsed]
        extra = [body for body in parsed if body not in wanted]
        repeated = [body for body in wanted if parsed.count(body) != 1]
        for body in missing:
            errors.append("orphan fragment: {}".format(body.splitlines()[0][:80]))
        for body in extra:
            errors.append("note is not a fragment: {}".format(body.splitlines()[0][:80]))
        for body in repeated:
            if body not in missing:
                errors.append("duplicate note: {}".format(body.splitlines()[0][:80]))
        if not errors:
            errors.append("rendered notes do not match the fragments")
    page = PAGE.read_text()
    if "release-2.14-notes.rst" not in page:
        errors.append("release-2.14.org does not include the rendered notes")
    return errors


def main(argv):
    errors, fragments = load()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    rendered = render(fragments)
    errors = check(fragments, rendered)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if "--check" not in argv:
        NOTES.parent.mkdir(parents=True, exist_ok=True)
        NOTES.write_text(rendered)
    elif NOTES.is_file() and NOTES.read_text() != rendered:
        print("release-2.14-notes.rst is stale; rebuild it from changelog.d", file=sys.stderr)
        return 1
    print("2.14.0 notes match {} fragments".format(len(fragments)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
