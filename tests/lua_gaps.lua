local dseams = require("dseams")

local cloud = dseams.system({0, 0, 0, 1, 0, 0}, {0, 0, 0, 4, 4, 4, 0, 0, 0})

local function expect(signature, fn)
  local ok, err = pcall(fn)
  assert(not ok, signature)
  local text = tostring(err)
  assert(text:find(signature, 1, true), text)
  assert(text:find("not in the public C API", 1, true), text)
end

