#!/usr/bin/env python3
"""Regenerate the Sollya minimax coefficients used by the kernels.

Sollya fpminimax builds a polynomial with binary64 coefficients.
supnorm returns an interval that contains the true maximum error, so the
recorded bound is the upper endpoint of that interval.

  exp(-t), t >= 0:
    t = (k + g) ln 2, g in [0, 1), k an integer
    exp(-t) = 2^{-k} * 2^{-g}
    2^{-g} is replaced by one polynomial on [0, 1]

  rsqrt on the mantissa [1/2, 1]:
    x = m * 2^e, m in [1/2, 1)
    1/sqrt(x) = 1/sqrt(m) * 2^{-e/2}
    The degree is the smallest whose relative supnorm is below 1e-15.
    The hot path keeps a correctly rounded square root; this polynomial
    is the certified alternative and is timed against it.

  ln on [1/2, 1], for a real power x^a = exp(a ln x) after range reduction.
"""

from __future__ import annotations

import json
import subprocess
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_H = ROOT / "src" / "include" / "internal" / "minimax_coeff.hpp"
OUT_JSON = Path(__file__).resolve().parent / "generated" / "sollya_bounds.json"


def sollya(script: str) -> str:
    done = subprocess.run(
        ["sollya"],
        input=script,
        text=True,
        capture_output=True,
        check=False,
    )
    text = done.stdout
    if "Error" in done.stderr and not text.strip():
        raise RuntimeError(done.stderr)
    return text


def fpminimax(expr: str, degree: int, lo: float, hi: float, mode: str) -> dict:
    fmt = ",".join(["D"] * (degree + 1))
    script = textwrap.dedent(
        f"""
        prec = 240;
        f = {expr};
        p = fpminimax(f, {degree}, [|{fmt}|], [{lo};{hi}], {mode});
        ea = supnorm(p, f, [{lo};{hi}], absolute, 1b-30);
        er = supnorm(p, f, [{lo};{hi}], relative, 1b-30);
        ed = supnorm(diff(p), diff(f), [{lo};{hi}], absolute, 1b-20);
        edr = supnorm(diff(p), diff(f), [{lo};{hi}], relative, 1b-20);
        print("ABS", sup(ea));
        print("REL", sup(er));
        print("DABS", sup(ed));
        print("DREL", sup(edr));
        for i from 0 to {degree} do print("C", i, coeff(p, i));
        """
    )
    coeffs = [None] * (degree + 1)
    bounds = {}
    for line in sollya(script).splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] in {"ABS", "REL", "DABS", "DREL"}:
            try:
                bounds[parts[0]] = float(parts[1])
            except ValueError:
                bounds[parts[0]] = None
        elif parts[0] == "C":
            coeffs[int(parts[1])] = float(parts[2])
    if any(c is None for c in coeffs):
        raise RuntimeError(f"missing coefficients for {expr}")
    return {
        "expression": expr,
        "degree": degree,
        "interval": [lo, hi],
        "mode": mode,
        "sup_absolute": bounds["ABS"],
        "sup_relative": bounds["REL"],
        "deriv_sup_absolute": bounds["DABS"],
        "deriv_sup_relative": bounds["DREL"],
        "coefficients": coeffs,
    }


def cxx_array(name: str, values: list[float]) -> str:
    # Hex floats round-trip to the same binary64 value.
    body = ",\n".join(f"    {v.hex()}" for v in values)
    return f"inline constexpr double {name}[{len(values)}] = {{\n{body}\n}};"


def main() -> None:
    exp2 = fpminimax("2^(-x)", 10, 0.0, 1.0, "relative")
    rsqrt = fpminimax("1/sqrt(x)", 18, 0.5, 1.0, "relative")
    ln = fpminimax("log(x)", 20, 0.5, 1.0, "absolute")

    report = {"exp2_neg": exp2, "rsqrt_mantissa": rsqrt, "ln_mantissa": ln}
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n")

    exp_d = [(i + 1) * exp2["coefficients"][i + 1] for i in range(exp2["degree"])]
    ln_d = [(i + 1) * ln["coefficients"][i + 1] for i in range(ln["degree"])]
    rs_d = [(i + 1) * rsqrt["coefficients"][i + 1] for i in range(rsqrt["degree"])]

    header = f"""#ifndef SEAMS_MINIMAX_COEFF_H_
#define SEAMS_MINIMAX_COEFF_H_

// Generated by discovery/sollya_minimax.py. Do not edit by hand.
// Each supnorm is the upper endpoint of the Sollya enclosure.

namespace seams {{
namespace minimax {{

// 2^{{-g}} on [0, 1]. Relative supnorm {exp2['sup_relative']:.6e}.
// Derivative relative supnorm {exp2['deriv_sup_relative']:.6e}.
{cxx_array("kExp2Neg", exp2["coefficients"])}

{cxx_array("kExp2NegDeriv", exp_d)}

inline constexpr double kExp2NegSupRelative = {exp2['sup_relative'].hex()};
inline constexpr double kExp2NegDerivSupRelative = {exp2['deriv_sup_relative'].hex()};

// 1/sqrt(m) on [1/2, 1]. Relative supnorm {rsqrt['sup_relative']:.6e}.
{cxx_array("kRsqrtMantissa", rsqrt["coefficients"])}

{cxx_array("kRsqrtMantissaDeriv", rs_d)}

inline constexpr double kRsqrtMantissaSupRelative = {rsqrt['sup_relative'].hex()};
inline constexpr int kRsqrtMantissaDegree = {rsqrt['degree']};

// ln(m) on [1/2, 1]. Absolute supnorm {ln['sup_absolute']:.6e}.
{cxx_array("kLnMantissa", ln["coefficients"])}

{cxx_array("kLnMantissaDeriv", ln_d)}

inline constexpr double kLnMantissaSupAbsolute = {ln['sup_absolute'].hex()};

}}  // namespace minimax
}}  // namespace seams

#endif
"""
    OUT_H.write_text(header)
    print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk != "coefficients"} for k, v in report.items()}, indent=2))


if __name__ == "__main__":
    main()
